#!/usr/bin/env python3
"""Supported-version matrix tooling (issue #124).

    python scripts/check_compat_matrix.py             # drift check (CI)
    python scripts/check_compat_matrix.py --write     # re-render docs/compatibility.md
    python scripts/check_compat_matrix.py --plan [ID] # JSON build matrix for compatibility.yml
    python scripts/check_compat_matrix.py --resolve ID  # KEY=VALUE lines, "latest"/"stable" resolved
    python scripts/check_compat_matrix.py --compare-vitest BASELINE.json CANDIDATE.json
    python scripts/check_compat_matrix.py --compare-cargo BASELINE.log CANDIDATE.log

The drift check fails when a pinned version in the repo (rust-toolchain.toml,
Cargo.toml/Cargo.lock, package.json/package-lock.json, workflow pins) differs
from compatibility-matrix.json's `supported` row, or when the rendered table in
docs/compatibility.md is stale. Changing a pin therefore means updating the
matrix in the same PR.
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MATRIX = ROOT / "compatibility-matrix.json"
DOC = ROOT / "docs" / "compatibility.md"
APPS = ("backend", "frontend")
TABLE_START = "<!-- compat-matrix:start (generated by scripts/check_compat_matrix.py --write) -->"
TABLE_END = "<!-- compat-matrix:end -->"
# compatibility.yml installs candidate toolchains on purpose; it is not a pin.
UNPINNED_WORKFLOWS = {"compatibility.yml"}
VERSION_KEYS = ("stellar_protocol", "rust", "soroban_sdk", "js_stellar_sdk")


def load_matrix(path: Path = MATRIX) -> dict:
    return json.loads(path.read_text())


def _read(root: Path, rel: str) -> str:
    return (root / rel).read_text()


def check_drift(matrix: dict, root: Path = ROOT) -> list[str]:
    """Every place the repo pins a version must agree with matrix['supported']."""
    s = matrix["supported"]
    errors: list[str] = []

    def expect(where: str, found: str | None, want: str) -> None:
        if found != want:
            errors.append(f"{where}: found {found!r}, matrix says {want!r}")

    m = re.search(r'^channel\s*=\s*"([^"]+)"', _read(root, "rust-toolchain.toml"), re.M)
    expect("rust-toolchain.toml channel", m and m.group(1), s["rust"])

    m = re.search(r'^soroban-sdk\s*=\s*\{\s*version\s*=\s*"([^"]+)"', _read(root, "Cargo.toml"), re.M)
    expect("Cargo.toml workspace soroban-sdk", m and m.group(1), s["soroban_sdk"])

    m = re.search(r'name = "soroban-sdk"\nversion = "([^"]+)"', _read(root, "Cargo.lock"))
    expect("Cargo.lock soroban-sdk", m and m.group(1), s["soroban_sdk"])

    for app in APPS:
        pkg = json.loads(_read(root, f"apps/{app}/package.json"))
        expect(f"apps/{app}/package.json @stellar/stellar-sdk",
               pkg.get("dependencies", {}).get("@stellar/stellar-sdk"), s["js_stellar_sdk"])
        lock = json.loads(_read(root, f"apps/{app}/package-lock.json"))
        locked = lock.get("packages", {}).get("node_modules/@stellar/stellar-sdk", {}).get("version")
        expect(f"apps/{app}/package-lock.json @stellar/stellar-sdk", locked, s["js_stellar_sdk"])

    for wf in sorted((root / ".github" / "workflows").glob("*.yml")):
        if wf.name in UNPINNED_WORKFLOWS:
            continue
        text = wf.read_text()
        for found in re.findall(r"^\s*toolchain:\s*['\"]?([\w.]+)", text, re.M):
            expect(f".github/workflows/{wf.name} toolchain", found, s["rust"])
        for found in re.findall(r"stellar-cli/releases/download/v([\d.]+)/", text):
            expect(f".github/workflows/{wf.name} stellar-cli", found, s["stellar_cli"])
        for found in re.findall(r"^\s*node-version:\s*['\"]?(\d+)", text, re.M):
            expect(f".github/workflows/{wf.name} node-version", found, s["node"])

    rendered = render_table(matrix)
    doc = DOC if root == ROOT else root / "docs" / "compatibility.md"
    current = doc.read_text() if doc.exists() else ""
    if rendered not in current:
        errors.append("docs/compatibility.md table is stale: run python scripts/check_compat_matrix.py --write")
    return errors


def _row(entry: dict, status: str) -> str:
    wallets = ", ".join(w["name"] for w in entry.get("wallets", [])) or "same as supported"
    cells = [
        f"`{entry['id']}`",
        status,
        str(entry.get("stellar_protocol", "")),
        f"`{entry.get('rust', '')}`",
        f"`{entry.get('soroban_sdk', '')}`",
        f"`{entry['stellar_cli']}`" if entry.get("stellar_cli") else "same as supported",
        f"`{entry.get('js_stellar_sdk', '')}`",
        f"Node {entry['node']}" if entry.get("node") else "same as supported",
        wallets,
    ]
    return "| " + " | ".join(cells) + " |"


def render_table(matrix: dict) -> str:
    header = (
        "| Combination | Status | Stellar protocol | Rust | soroban-sdk | Stellar CLI | @stellar/stellar-sdk | Node | Wallets |\n"
        "|---|---|---|---|---|---|---|---|---|"
    )
    rows = [_row(matrix["supported"], "**Supported**: tested on every PR and weekly")]
    for c in matrix["candidates"]:
        status = "Candidate (required)" if c.get("required") else "Candidate (report only)"
        rows.append(_row(c, status))
    return "\n".join([TABLE_START, header, *rows, TABLE_END])


def write_doc(matrix: dict) -> None:
    text = DOC.read_text()
    start, end = text.index(TABLE_START), text.index(TABLE_END) + len(TABLE_END)
    DOC.write_text(text[:start] + render_table(matrix) + text[end:])


def plan(matrix: dict, only: str | None = None) -> list[dict]:
    """The build matrix: the supported row (always, as the baseline) plus candidates."""
    s = matrix["supported"]
    entries = [{"id": s["id"], "required": True, **{k: s[k] for k in VERSION_KEYS}}]
    for c in matrix["candidates"]:
        entries.append({"id": c["id"], "required": bool(c.get("required")), **{k: c[k] for k in VERSION_KEYS}})
    if only:
        entries = [e for e in entries if e["id"] in (only, s["id"])]
        if len(entries) < 2 and only != s["id"]:
            raise SystemExit(f"unknown candidate {only!r}")
    return entries


def _fetch_json(url: str) -> dict:
    req = urllib.request.Request(url, headers={"User-Agent": "smile4money-compat-check"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def resolve(matrix: dict, entry_id: str, fetch=_fetch_json) -> dict[str, str]:
    """Concrete versions for one plan entry, resolving "latest" against the registries."""
    entry = next(e for e in plan(matrix) if e["id"] == entry_id)
    out = {k: str(entry[k]) for k in VERSION_KEYS}
    if out["soroban_sdk"] == "latest":
        out["soroban_sdk"] = fetch("https://crates.io/api/v1/crates/soroban-sdk")["crate"]["max_stable_version"]
    if out["js_stellar_sdk"] == "latest":
        out["js_stellar_sdk"] = fetch("https://registry.npmjs.org/@stellar%2Fstellar-sdk")["dist-tags"]["latest"]
    if out["stellar_protocol"] == "latest":
        out["stellar_protocol"] = out["soroban_sdk"].split(".")[0]
    return out


def _failed_tests(report: dict) -> set[str]:
    failed = set()
    for suite in report.get("testResults", []):
        name = Path(suite.get("name", "")).name
        if suite.get("status") == "failed" and not suite.get("assertionResults"):
            failed.add(f"{name} (suite failed to load)")
        for t in suite.get("assertionResults", []):
            if t.get("status") == "failed":
                failed.add(f"{name} > {t.get('fullName') or t.get('title')}")
    return failed


def compare_vitest(baseline: dict, candidate: dict) -> list[str]:
    """Tests that fail with the candidate but pass (or don't fail) on the baseline."""
    return sorted(_failed_tests(candidate) - _failed_tests(baseline))


def _failed_cargo(log: str) -> set[str]:
    failed = set(re.findall(r"^test (\S+) \.\.\. FAILED$", log, re.M))
    for crate in re.findall(r"^error: could not compile `([^`]+)`", log, re.M):
        failed.add(f"{crate} (does not compile)")
    return failed


def compare_cargo(baseline_log: str, candidate_log: str) -> list[str]:
    """Rust tests (or crates) that fail only with the candidate versions."""
    return sorted(_failed_cargo(candidate_log) - _failed_cargo(baseline_log))


def _report_new(new: list[str]) -> int:
    for t in new:
        print(f"NEW FAILURE: {t}")
    print(f"{len(new)} failure(s) only with the candidate versions")
    return 1 if new else 0


def main(argv: list[str]) -> int:
    matrix = load_matrix()
    if argv[:1] == ["--write"]:
        write_doc(matrix)
        return 0
    if argv[:1] == ["--plan"]:
        print(json.dumps(plan(matrix, argv[1] if len(argv) > 1 and argv[1] else None)))
        return 0
    if argv[:1] == ["--resolve"]:
        for k, v in resolve(matrix, argv[1]).items():
            print(f"{k.upper()}={v}")
        return 0
    if argv[:1] == ["--compare-vitest"]:
        return _report_new(compare_vitest(json.loads(Path(argv[1]).read_text()), json.loads(Path(argv[2]).read_text())))
    if argv[:1] == ["--compare-cargo"]:
        return _report_new(compare_cargo(Path(argv[1]).read_text(), Path(argv[2]).read_text()))
    errors = check_drift(matrix)
    for e in errors:
        print(f"DRIFT: {e}")
    if errors:
        print("Update compatibility-matrix.json (and re-run --write) in the same PR as the pin change.")
        return 1
    print("compatibility matrix matches the repo's pinned versions")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
